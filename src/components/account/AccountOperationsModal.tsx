// Generate Netscape HTTP Cookie file string
function generateNetscapeCookie(item: PortfolioItem): string {
  const p = item.platform.toLowerCase();
  let domain = `.${p}.com`;
  if (p.includes('steam')) domain = '.steamcommunity.com';
  else if (p.includes('discord')) domain = '.discord.com';
  else if (p.includes('tiktok')) domain = '.tiktok.com';
  else if (p.includes('facebook') || p.includes('meta')) domain = '.facebook.com';
  else if (p.includes('x') || p.includes('twitter')) domain = '.x.com';
  else if (p.includes('psn') || p.includes('playstation')) domain = '.playstation.com';

  const token = item.credentials?.sessionCookies || `lr_sess_${item.accountId}_auth`;
  const expiry = Math.floor(Date.now() / 1000) + 86400 * 30;
  return `# Netscape HTTP Cookie File
# Generated by Logs Rent Account Operations Engine
# Platform: ${item.platform} • ID #${item.accountId} • Grade ${item.grade}
# Compatible with: Cookie-Editor, EditThisCookie, Dolphin Anty, AdsPower
${domain}\tTRUE\t/\tTRUE\t${expiry}\tsession_token\t${token}
${domain}\tTRUE\t/\tTRUE\t${expiry}\tauth_user\t${item.credentials?.username || 'user'}
${domain}\tTRUE\t/\tTRUE\t${expiry}\tlr_verified\t1
`;
}

// Generate JSON Cookie array string
function generateJsonCookie(item: PortfolioItem): string {
  const p = item.platform.toLowerCase();
  let domain = `.${p}.com`;
  if (p.includes('steam')) domain = '.steamcommunity.com';
  else if (p.includes('discord')) domain = '.discord.com';
  else if (p.includes('tiktok')) domain = '.tiktok.com';
  else if (p.includes('facebook') || p.includes('meta')) domain = '.facebook.com';
  else if (p.includes('x') || p.includes('twitter')) domain = '.x.com';
  else if (p.includes('psn') || p.includes('playstation')) domain = '.playstation.com';

  const token = item.credentials?.sessionCookies || `lr_sess_${item.accountId}_auth`;
  const expiry = Math.floor(Date.now() / 1000) + 86400 * 30;
  const cookies = [
    {
      name: 'session_token',
      value: token,
      domain,
      path: '/',
      secure: true,
      httpOnly: true,
      expirationDate: expiry,
      sameSite: 'Lax'
    },
    {
      name: 'auth_user',
      value: item.credentials?.username || `user_${item.accountId}`,
      domain,
      path: '/',
      secure: true,
      httpOnly: false,
      expirationDate: expiry,
      sameSite: 'Lax'
    },
    {
      name: 'lr_vault_status',
      value: 'active_session',
      domain,
      path: '/',
      secure: true,
      httpOnly: true,
      expirationDate: expiry,
      sameSite: 'Lax'
    }
  ];
  return JSON.stringify(cookies, null, 2);
}

// Deterministic TOTP code generator
function getTotpCode(secret: string = 'JBSWY3DPEHPK3PXP'): { code: string; secondsLeft: number } {
  const step = 30;
  const now = Math.floor(Date.now() / 1000);
  const timeSlot = Math.floor(now / step);
  const secondsLeft = step - (now % step);

  let hash = 0;
  const str = secret + timeSlot.toString();
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) % 1000000;
  }
  const code = hash.toString().padStart(6, '0');
  return { code, secondsLeft };
}

// Secure password generator
function generateSecurePassword(): string {
  const upper = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  const lower = 'abcdefghijkmnopqrstuvwxyz';
  const digits = '23456789';
  const specials = '!@#$%&*';
  const all = upper + lower + digits + specials;
  let pass = '';
  pass += upper[Math.floor(Math.random() * upper.length)];
  pass += lower[Math.floor(Math.random() * lower.length)];
  pass += digits[Math.floor(Math.random() * digits.length)];
  pass += specials[Math.floor(Math.random() * specials.length)];
  for (let i = 4; i < 16; i++) {
    pass += all[Math.floor(Math.random() * all.length)];
  }
  return pass.split('').sort(() => 0.5 - Math.random()).join('');
}

